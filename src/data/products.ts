export function getProductBySlug(slug: string): Product | undefined {
  return onlyPublished(products).find((p) => p.slug === slug);
}

export function getProductsByCategory(categorySlug: string): Product[] {
  const published = onlyPublished(products);
  const node = getTaxonomyNodeBySlug(categorySlug);
  if (node) {
    const targets = new Set<string>([node.slug]);
    for (const d of getTaxonomyDescendants(node.id)) targets.add(d.slug);
    return published.filter((p) => {
      const m = productMappings[p.id];
      if (!m) return false;
      return targets.has(m.categorySlug) || targets.has(m.subcategorySlug) || targets.has(m.productTypeSlug);
    });
  }
  const children = sectionChildren[categorySlug];
  if (children) return published.filter((p) => p.categorySlug && children.includes(p.categorySlug));
  return published.filter((p) => p.categorySlug === categorySlug);
}

export function getCategoryBySlug(slug: string): CategoryInfo | undefined {
  const node = getTaxonomyNodeBySlug(slug);
  if (node) {
    return {
      slug: node.slug,
      name: node.nameEn,
      nameAr: node.nameAr,
      description: node.descriptionEn ?? "",
      descriptionAr: node.descriptionAr ?? "",
    };
  }
  return categories.find((c) => c.slug === slug) ?? sectionCategories.find((c) => c.slug === slug);
}

