export function getRelatedProducts(product: Product, count: number = 4): Product[] {
  return onlyPublished(products)
    .filter((p) => p.id !== product.id && (p.categorySlug === product.categorySlug || p.brand === product.brand))
    .slice(0, count);
}

const taxonomyNameById = new Map<string, string[]>();
for (const m of Object.values(productMappings)) {
  const names: string[] = [];
  for (const slug of [m.categorySlug, m.subcategorySlug, m.productTypeSlug]) {
    const node = taxonomy.find((n) => n.slug === slug);
    if (node) {
      if (node.nameAr) names.push(node.nameAr);
      if (node.nameEn) names.push(node.nameEn.toLowerCase());
      for (const alias of node.legacySlugs ?? []) {
        names.push(alias.toLowerCase());
      }
    }
  }
  taxonomyNameById.set(m.productId, names);
}

export function searchProducts(query: string): Product[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return onlyPublished(products).filter(
    (p) =>
      p.name.ar.includes(q) ||
      p.name.en.toLowerCase().includes(q) ||
      p.brand.toLowerCase().includes(q) ||
      (p.brandAr && p.brandAr.includes(q)) ||
      (p.categoryAr && p.categoryAr.includes(q)) ||
      p.description.ar.includes(q) ||
      p.description.en.toLowerCase().includes(q) ||
      (p.searchAliases && p.searchAliases.some((alias) => alias.toLowerCase().includes(q))) ||
      taxonomyNameById.get(p.id)?.some((name) => name.includes(q)) ||
      (p.categorySlug && getTaxonomyNodeBySlug(p.categorySlug)?.legacySlugs?.some((l) => l.includes(q)))
  );
}

